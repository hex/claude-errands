test('files brought in from a remote branch that was ahead when the job was sent are named with that remote branch', () => {
  const origin = scratch()
  const dir = realpathSync(mkdtempSync(join(tmpdir(), 'claude-errands-changes-clone-')))
  execFileSync('git', ['clone', '-q', origin.dir, dir])
  const run = (...args: string[]): void => { execFileSync('git', ['-C', dir, '-c', 'user.name=alice', '-c', 'user.email=alice@example.com', ...args]) }
  run('checkout', '-q', '-b', 'job')
  origin.write('docs/up.md', 'upstream\n')
  origin.run('add', '-A')
  origin.run('commit', '-q', '-m', 'upstream doc')
  const upstream = execFileSync('git', ['-C', origin.dir, 'rev-parse', '--short', 'main'], { encoding: 'utf8' }).trim()
  run('fetch', '-q', 'origin')
  const baseline = captureBaseline(dir)
  run('rebase', '-q', 'origin/main')
  const report = reportChanges(dir, baseline, ['src/**'])
  assert.deepEqual([report.outsideAllowList, report.broughtIn], [[], { from: 'origin/main', commit: upstream, paths: ['docs/up.md'] }])
})
