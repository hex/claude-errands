test('a commit outside the allow-list is still reported when the agent detaches HEAD at it', () => {
  const repo = jobBranchBehindMain()
  repo.run('rebase', '-q', 'main')
  repo.commit('secrets.md', 's\n', 'add secrets')
  repo.run('checkout', '-q', '--detach')
  const report = reportChanges(repo.dir, repo.baseline, ['src/**'])
  assert.deepEqual([report.outsideAllowList, report.broughtIn], [['secrets.md'], { from: 'main', commit: repo.upstream, paths: ['docs/up.md'] }])
  assert.deepEqual(report.commits.map(line => line.replace(/^\S+ /, '')), ['add secrets'])
})
